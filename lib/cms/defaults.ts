import {
  aboutFocus,
  aboutStack,
  aiCapabilities,
  contactAvailability,
  contributions,
  experiences,
  heroHighlights,
  personalInfo,
  professionalHighlights,
  projects,
  skillGroups,
} from "@/data/portfolio-data";
import { THEME_PRESETS, type CmsSiteData } from "./types";

function id(prefix: string, value: string) {
  return `${prefix}-${value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}`;
}

export function createDefaultSiteData(): CmsSiteData {
  return {
    personalInfo: {
      name: personalInfo.name,
      role: personalInfo.role,
      location: personalInfo.location,
      headline: personalInfo.headline,
      summary: personalInfo.summary,
      email: personalInfo.email,
      phone: personalInfo.phone,
      linkedin: personalInfo.linkedin,
      github: "https://github.com/Pratikchogale1410/",
      portfolio: personalInfo.portfolio,
      resumeUrl: personalInfo.resumeUrl,
      profileImage: "/images/profile.jpg",
      logoUrl: "",
    },
    hero: {
      heading: personalInfo.name,
      subtitle: personalInfo.role,
      description: "Building production-ready AI-powered applications, CRM systems & scalable web products.",
      ctaText: "View My Work",
      ctaUrl: "#projects",
      highlights: [...heroHighlights],
    },
    about: {
      title: "Product-minded full stack development",
      description: personalInfo.summary,
      focus: [...aboutFocus],
      stack: [...aboutStack],
    },
    highlights: professionalHighlights.map((item, index) => ({
      id: id("highlight", item.title || String(index)),
      title: item.title,
      detail: item.detail,
      metric: item.metric,
    })),
    experiences: experiences.map((item, index) => ({
      id: id("exp", `${item.role}-${index}`),
      role: item.role,
      company: item.company,
      period: item.period,
      tags: [...item.tags],
      points: [...item.points],
      visibility: "published" as const,
    })),
    contributions: contributions.map((item, index) => ({
      id: id("contrib", item.title || String(index)),
      title: item.title,
      detail: item.detail,
    })),
    skillGroups: skillGroups.map((group, groupIndex) => ({
      id: id("skill-group", group.category || String(groupIndex)),
      category: group.category,
      skills: group.skills.map((skill, skillIndex) => ({
        id: id("skill", `${group.category}-${skill.name || skillIndex}`),
        name: skill.name,
        description: skill.description,
      })),
    })),
    aiCapabilities: [...aiCapabilities],
    projects: projects.map((project, index) => ({
      id: project.id,
      order: index + 1,
      featured: Boolean(project.featured),
      visibility: "published" as const,
      category: project.category,
      name: project.name,
      period: project.period,
      startDate: "",
      endDate: "",
      role: "Full Stack Developer",
      image: project.image,
      description: project.description,
      problem: project.problem,
      solution: project.solution,
      stack: [...project.stack],
      features: [...project.features],
      contributions: [...project.contributions],
      demo: project.demo,
      github: project.github || "",
    })),
      contactAvailability: [...contactAvailability],
    theme: { ...THEME_PRESETS.midnight },
    media: [
      {
        id: "media-profile",
        url: "/images/profile.jpg",
        filename: "profile.jpg",
        type: "image/jpeg",
        size: 0,
        kind: "profile",
        createdAt: new Date().toISOString(),
      },
      {
        id: "media-dermaplast",
        url: "/projects/dermaplastcrm.png",
        filename: "dermaplastcrm.png",
        type: "image/png",
        size: 0,
        kind: "project",
        createdAt: new Date().toISOString(),
      },
      {
        id: "media-applysathi",
        url: "/projects/applysathi.png",
        filename: "applysathi.png",
        type: "image/png",
        size: 0,
        kind: "project",
        createdAt: new Date().toISOString(),
      },
      {
        id: "media-evcs",
        url: "/projects/EVCS.jpeg",
        filename: "EVCS.jpeg",
        type: "image/jpeg",
        size: 0,
        kind: "project",
        createdAt: new Date().toISOString(),
      },
    ],
    updatedAt: new Date().toISOString(),
  };
}
